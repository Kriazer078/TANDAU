  /// Build chat prompt with optional intent, user context, and few-shot examples
  static String buildChatPrompt({
    String? userContext,
    String? intentInstruction,
    bool includeFewShot = true,
  }) {
    final buffer = StringBuffer(chat);

    if (includeFewShot) {
      buffer.write(fewShotExamples);
    }

    if (intentInstruction != null && intentInstruction.isNotEmpty) {
      buffer.write(intentInstruction);
    }

    if (userContext != null && userContext.isNotEmpty) {
      buffer.write(
          '\n\n### КОНТЕКСТ ТЕКУЩЕГО ПОЛЬЗОВАТЕЛЯ (УЧИТЫВАЙ ПРИ ОТВЕТЕ):\n$userContext');
    }

    return buffer.toString();
  }

